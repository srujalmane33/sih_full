// Helper functions for equipment analytics
export const getEquipmentSummaryMetrics = (equipmentList = INITIAL_EQUIPMENT_DATA) => {
  const totalCount = equipmentList.length;
  const operationalCount = equipmentList.filter((e) => e.status === 'Operational').length;
  const maintenanceCount = equipmentList.filter((e) => e.status === 'Maintenance Required' || e.status === 'Degraded').length;
  const breakdownCount = equipmentList.filter((e) => e.status === 'Breakdown').length;

  const totalDowntimeHours = equipmentList.reduce((acc, e) => acc + e.avgDowntimeHours, 0);
  const avgDowntime = (totalDowntimeHours / (totalCount || 1)).toFixed(1);

  const avgAvailability = (
    equipmentList.reduce((acc, e) => acc + e.availabilityPct, 0) / (totalCount || 1)
  ).toFixed(1);

  const avgMtbf = Math.round(equipmentList.reduce((acc, e) => acc + e.mtbfHours, 0) / (totalCount || 1));
  const avgMttr = (equipmentList.reduce((acc, e) => acc + e.mttrHours, 0) / (totalCount || 1)).toFixed(1);

  return {
    totalCount,
    operationalCount,
    maintenanceCount,
    breakdownCount,
    avgDowntime,
    avgAvailability,
    avgMtbf,
    avgMttr,
    totalDowntimeHours: totalDowntimeHours.toFixed(1),
  };
};

